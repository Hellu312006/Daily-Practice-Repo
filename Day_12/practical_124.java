package Day_12;

public class practical_124 {
    public static void main(String[] args) {
        int a = 20;
        int b = 30;

        System.out.println(a > b);
        System.out.println(a < b);
        System.out.println(a == b);
        // Note: Java is statically typed and does not have the '===' operator.
        // '==' compares values directly for primitive types like int.
        System.out.println(a == b);
    }
}
